// Builds the installable web app into dist/: copies the browser build plus the
// shared data/ and localization/, vendors three.js (no CDN needed offline),
// and generates a versioned service worker that precaches the app shell.
import fs from 'node:fs';
import path from 'node:path';
import crypto from 'node:crypto';

const ROOT = path.resolve(path.dirname(new URL(import.meta.url).pathname), '..');
const DIST = path.join(ROOT, 'dist');
fs.rmSync(DIST, { recursive: true, force: true });
const copy = (from, to) => { fs.mkdirSync(path.dirname(path.join(DIST, to)), { recursive: true }); fs.copyFileSync(path.join(ROOT, from), path.join(DIST, to)); };
const copyDir = (from, to) => { for (const f of fs.readdirSync(path.join(ROOT, from))) { const s = path.join(from, f); if (fs.statSync(path.join(ROOT, s)).isDirectory()) copyDir(s, path.join(to, f)); else copy(s, path.join(to, f)); } };

copyDir('web/js', 'js');
copyDir('web/icons', 'icons');
if (fs.existsSync(path.join(ROOT, 'web/assets'))) copyDir('web/assets', 'assets');
copyDir('data', 'data');
copyDir('localization', 'localization');
copy('web/manifest.webmanifest', 'manifest.webmanifest');
copy('web/visual.css', 'visual.css');
copy('node_modules/three/build/three.module.js', 'vendor/three.module.js');

let html = fs.readFileSync(path.join(ROOT, 'web/index.html'), 'utf8');
html = html.replace(/https:\/\/cdn\.jsdelivr\.net\/npm\/three@[\d.]+\/build\/three\.module\.js/, './vendor/three.module.js');
html = html.replace('<meta charset="utf-8">', '<meta charset="utf-8">\n<meta name="atlas-pwa" content="1">');
fs.writeFileSync(path.join(DIST, 'index.html'), html);

const files = [];
const walk = d => { for (const f of fs.readdirSync(d)) { const p = path.join(d, f); fs.statSync(p).isDirectory() ? walk(p) : files.push(path.relative(DIST, p).split(path.sep).join('/')); } };
walk(DIST);
const hash = crypto.createHash('sha1');
for (const f of files.sort()) hash.update(f).update(fs.readFileSync(path.join(DIST, f)));
const version = hash.digest('hex').slice(0, 10);
const shell = ['./', ...files.filter(f => f !== 'index.html')];
const sw = `// Generated by tools/build-web.mjs — app shell precache (offline play).
const CACHE = 'atlas-air-${version}';
const SHELL = ${JSON.stringify(shell)};
self.addEventListener('install', e => { e.waitUntil(caches.open(CACHE).then(c => c.addAll(SHELL)).then(() => self.skipWaiting())); });
self.addEventListener('activate', e => { e.waitUntil(caches.keys().then(keys => Promise.all(keys.filter(k => k !== CACHE).map(k => caches.delete(k)))).then(() => self.clients.claim())); });
self.addEventListener('fetch', e => {
  const req = e.request;
  if (req.method !== 'GET') return;
  const url = new URL(req.url);
  if (url.origin === location.origin) {
    // App shell: cache first, fall back to network; navigations fall back to index.
    e.respondWith(caches.match(req, { ignoreSearch: true }).then(hit => hit || fetch(req).catch(() => req.mode === 'navigate' ? caches.match('./') : Response.error())));
  } else if (url.hostname.endsWith('fonts.googleapis.com') || url.hostname.endsWith('fonts.gstatic.com')) {
    // Web fonts: stale-while-revalidate so text keeps its font offline.
    e.respondWith(caches.open(CACHE).then(c => c.match(req).then(hit => { const net = fetch(req).then(r => { c.put(req, r.clone()); return r; }).catch(() => hit); return hit || net; })));
  }
});
`;
fs.writeFileSync(path.join(DIST, 'sw.js'), sw);
console.log(`dist/ built: ${files.length + 1} files, cache ${version}`);
